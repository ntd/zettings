static void dump(const char *name, const void *data, size_t size)
{
    int n;
    const uint8_t *byte = data;
    printf("sizeof(%s) = %d bytes\n", name, (int) size);
    for (n = 0; n < size; ++n) {
        printf("0x%02X,%s", byte[n], ((n % 8) == 7) ? "\n" : " ");
    }
    printf("\n");
}

